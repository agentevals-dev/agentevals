class RubricBasedFinalResponseQualityV1WithHistory(RubricBasedFinalResponseQualityV1Evaluator):
    """Evaluates rubric properties for turn i with context from turns 0..i-1."""
    def __init__(self, eval_metric):
        super().__init__(eval_metric)
        self._auto_rater_prompt_template = _RUBRIC_FINAL_RESPONSE_WITH_HISTORY_PROMPT
        self._preceding_by_invocation: dict[int, list[Invocation]] = {}
    async def evaluate_invocations(
        self,
        actual_invocations: list[Invocation],
        expected_invocations: Optional[list[Invocation]] = None,
        conversation_scenario: Optional[ConversationScenario] = None,
    ) -> EvaluationResult:
        # Pre-map preceding turns for each invocation
        self._preceding_by_invocation = {
            id(actual): actual_invocations[:idx]
            for idx, actual in enumerate(actual_invocations)
        }
        try:
            return await super().evaluate_invocations(
                actual_invocations=actual_invocations,
                expected_invocations=expected_invocations,
                conversation_scenario=conversation_scenario,
            )
        finally:
            self._preceding_by_invocation.clear()
    def format_auto_rater_prompt(
        self,
        actual_invocation: Invocation,
        expected_invocation: Optional[Invocation],
    ) -> str:
        # 1. Effective rubrics
        self.create_effective_rubrics_list(actual_invocation.rubrics)
        user_input = get_text_from_content(actual_invocation.user_content)
        include_intermediate = self._criterion.include_intermediate_responses_in_final
        final_response = (
            get_text_from_content(
                actual_invocation,
                include_intermediate_responses_in_final=include_intermediate,
            )
            or ""
        )
        rubrics_text = "\n".join(
            [f"*  [id: {r.rubric_id}] {r.rubric_content.text_property}" for r in self.get_effective_rubrics_list()]
        )
        developer_instructions = ""
        tool_declarations = "Agent has no tools."
        response_steps = get_tool_calls_and_responses_as_json_str(actual_invocation.intermediate_data)
        grounding_metadata = get_grounding_metadata_as_json_str(actual_invocation.intermediate_data)
        app_details = actual_invocation.app_details
        if app_details:
            agent_name = None
            if (
                isinstance(actual_invocation.intermediate_data, InvocationEvents)
                and actual_invocation.intermediate_data.invocation_events
            ):
                agent_name = actual_invocation.intermediate_data.invocation_events[0].author
            elif app_details.agent_details:
                agent_name = next(iter(app_details.agent_details))
            if agent_name:
                developer_instructions = app_details.get_developer_instructions(agent_name=agent_name)
            tool_declarations = get_tool_declarations_as_json_str(app_details)
        # 2. Preceding conversation
        preceding = self._preceding_by_invocation.get(id(actual_invocation), [])
        preceding_text = format_preceding_dialogue(preceding)
        return self._auto_rater_prompt_template.format(
            preceding_conversation=preceding_text,
            developer_instructions=developer_instructions,
            tool_declarations=tool_declarations,
            user_input=user_input,
            response_steps=response_steps,
            grounding_metadata=grounding_metadata,
            final_response=final_response,
            rubrics=rubrics_text,
        )
